					return DXGI_FORMAT_B8G8R8A8_UNORM_SRGB;
				case RHI_ResourceFormat::RHI_RESOURCE_FORMAT_R16_UINT:
					return DXGI_FORMAT_R16_UINT;
				case RHI_ResourceFormat::RHI_RESOURCE_FORMAT_R16_SINT:
					return DXGI_FORMAT_R16_SINT;
